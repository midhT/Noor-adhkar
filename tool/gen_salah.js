const fs=require('fs');
const src=fs.readFileSync('/home/claude/src/v3/noor-adhkar/www/v3.js','utf8');
const m=src.match(/const salah = (\[[\s\S]*?\n  \]);/);
const salah=eval(m[1]);
const esc=s=>"'"+s.replace(/\\/g,'\\\\').replace(/'/g,"\\'").replace(/\$/g,'\\$').replace(/\n/g,'\\n')+"'";
let out="// GENERATED from Noor V3 (www/v3.js) by tool/gen_salah.js — content is unchanged from V3.\n// Arabic, transliteration, translations and notes must be reviewed by a qualified\n// Hanafi scholar/editor before public release (see docs/04_KNOWN_LIMITATIONS.md).\n\nclass SalahStep {\n  final String title, place, arabic, latin, meaning, source;\n  const SalahStep(this.title, this.place, this.arabic, this.latin, this.meaning, this.source);\n}\n\nconst salahGuide = <SalahStep>[\n";
for(const x of salah) out+=`  SalahStep(${esc(x.title)}, ${esc(x.place)}, ${esc(x.ar)}, ${esc(x.latin)}, ${esc(x.meaning)}, ${esc(x.source)}),\n`;
out+="];\n";
fs.writeFileSync('lib/core/data/salah_guide.dart',out);
